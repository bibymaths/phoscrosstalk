def _neural_simulate_dense(
    *,
    model,
    K: int,
    M: int,
    N: int,
    mechanism: str,
    theta_j: jax.Array,
    y0_j: jax.Array,
    t0_val: float,
    t_dense: np.ndarray,
    prev_site_idx_j: jax.Array,
    Cg_j: jax.Array,
    Cl_j: jax.Array,
    K_sk_j: jax.Array,
    R_j: jax.Array,
    La_j: jax.Array,
    spi_j: jax.Array,
    k2p_j: jax.Array,
    rmp_j: jax.Array,
    rmk_j: jax.Array,
    t_max: float,
    k_act_init_fn,
    s_prod_init_fn,
    rtol: float,
    atol: float,
    dt0: float,
    max_steps: int,
    rna_relax: float,
    abundance_max: float,
) -> dict:
    """Run the neural ODE over a time grid and return solution arrays."""
    t_max_j = jnp.asarray(t_max, dtype=jnp.float64)

    def _k_hat_fn(t):
        t_norm = jnp.clip(t / t_max_j, 0.0, 1.0)
        k_prior = jnp.clip(k_act_init_fn(t), 0.0, None)
        s_prior = jnp.clip(s_prod_init_fn(t), 0.0, None)
        features = jnp.concatenate(
            [jnp.asarray([t_norm], dtype=jnp.float64), k_prior, s_prior]
        )
        k_hat, _ = model(features)
        return k_hat

    def _s_hat_fn(t):
        t_norm = jnp.clip(t / t_max_j, 0.0, 1.0)
        k_prior = jnp.clip(k_act_init_fn(t), 0.0, None)
        s_prior = jnp.clip(s_prod_init_fn(t), 0.0, None)
        features = jnp.concatenate(
            [jnp.asarray([t_norm], dtype=jnp.float64), k_prior, s_prior]
        )
        _, s_hat = model(features)
        return s_hat

    rhs_fn = make_rhs(
        K,
        M,
        N,
        mechanism,
        k_act_fn=_k_hat_fn,
        s_prod_fn=_s_hat_fn,
        rna_relax=rna_relax,
        abundance_max=abundance_max,
    )

    t_dense_j = jnp.asarray(t_dense, dtype=jnp.float64)
    t1_val = float(t_dense[-1])

    ode_static_args = (
        theta_j,
        Cg_j,
        Cl_j,
        spi_j,
        K_sk_j,
        R_j,
        La_j,
        k2p_j,
        rmp_j,
        rmk_j,
        prev_site_idx_j,
    )

    sol = diffrax.diffeqsolve(
        diffrax.ODETerm(rhs_fn),
        diffrax.Tsit5(),
        t0=t0_val,
        t1=t1_val,
        dt0=dt0,
        y0=y0_j,
        args=ode_static_args,
        saveat=diffrax.SaveAt(ts=t_dense_j),
        stepsize_controller=diffrax.PIDController(rtol=rtol, atol=atol),
        max_steps=max_steps,
        throw=False,
    )

    xs = np.asarray(sol.ys)
    R_sim = np.clip(xs[:, :K].T, 0.0, None)
    P_sim = np.clip(xs[:, 3 * K + M :].T, 0.0, None)
    A_sim = np.clip(xs[:, 2 * K : 3 * K].T, 0.0, abundance_max)
    return {"P_sim": P_sim, "A_sim": A_sim, "R_sim": R_sim, "xs": xs}


