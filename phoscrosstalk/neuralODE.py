def _evaluate_mechanistic_rate_priors(k_act_fn, s_prod_fn, t_obs: np.ndarray):
    """
    Evaluate mechanistic k_act/s_prod priors at observed times.

    Tries a JAX-vmap path first. Falls back to the Python loop if the derived
    rate closures contain NumPy/Python logic that is not JAX-traceable.
    """
    t_obs_j = jnp.asarray(t_obs, dtype=jnp.float64)

    try:
        k_vals_j = jax.vmap(k_act_fn)(t_obs_j)      # (T_obs, K)
        s_vals_j = jax.vmap(s_prod_fn)(t_obs_j)    # (T_obs, K)

        k_vals = np.asarray(k_vals_j, dtype=np.float64).T
        s_vals = np.asarray(s_vals_j, dtype=np.float64).T

        if not np.all(np.isfinite(k_vals)) or not np.all(np.isfinite(s_vals)):
            raise FloatingPointError("non-finite vmap rate prior values")

        return k_vals, s_vals, "jax.vmap"

    except Exception:
        k_vals = np.stack(
            [np.asarray(k_act_fn(float(ti)), dtype=np.float64) for ti in t_obs],
            axis=1,
        )
        s_vals = np.stack(
            [np.asarray(s_prod_fn(float(ti)), dtype=np.float64) for ti in t_obs],
            axis=1,
        )
        return k_vals, s_vals, "python-loop"

def _eval_neural_rates_on_observed_grid(
    model,
    *,
    t_obs_j: jax.Array,
    t_max_j: jax.Array,
    k_act_init_obs_j: jax.Array,
    s_prod_init_obs_j: jax.Array,
):
    """
    Evaluate neural k_hat/s_hat on all observed times using vmap.

    Inputs:
        k_act_init_obs_j: (K, T_obs)
        s_prod_init_obs_j: (K, T_obs)

    Returns:
        k_hats_obs: (K, T_obs)
        s_hats_obs: (K, T_obs)
    """
    t_norms = jnp.clip(t_obs_j / t_max_j, 0.0, 1.0)[:, None]
    k_priors_obs = k_act_init_obs_j.T
    s_priors_obs = s_prod_init_obs_j.T
    features_obs = jnp.concatenate([t_norms, k_priors_obs, s_priors_obs], axis=1)

    k_hats_obs, s_hats_obs = jax.vmap(model)(features_obs)
    return k_hats_obs.T, s_hats_obs.T

def _make_optax_optimizer(neural_cfg):
    """Build an Optax optimizer from neural_cfg."""
    name = str(getattr(neural_cfg, "optimizer", "adabelief")).lower()
    lr = float(getattr(neural_cfg, "learning_rate", 1e-3))
    weight_decay = float(getattr(neural_cfg, "weight_decay", 0.0))
    grad_clip = float(getattr(neural_cfg, "grad_clip", 1.0))

    transforms = []
    if grad_clip > 0:
        transforms.append(optax.clip_by_global_norm(grad_clip))

    if name == "adabelief":
        transforms.append(optax.adabelief(learning_rate=lr))
    elif name == "adamw":
        transforms.append(optax.adamw(learning_rate=lr, weight_decay=weight_decay))
    elif name == "adam":
        transforms.append(optax.adam(learning_rate=lr))
    elif name == "adan":
        transforms.append(optax.adan(learning_rate=lr, weight_decay=weight_decay))
    elif name == "radam":
        transforms.append(optax.radam(learning_rate=lr))
    elif name == "nadam":
        transforms.append(optax.nadam(learning_rate=lr))
    elif name == "nadamw":
        transforms.append(optax.nadamw(learning_rate=lr, weight_decay=weight_decay))
    elif name == "lion":
        transforms.append(optax.lion(learning_rate=lr, weight_decay=weight_decay))
    elif name == "sgd":
        momentum = getattr(neural_cfg, "momentum", None)
        transforms.append(
            optax.sgd(
                learning_rate=lr,
                momentum=None if momentum is None else float(momentum),
                nesterov=bool(getattr(neural_cfg, "nesterov", False)),
            )
        )
    else:
        raise ValueError(
            f"Unsupported neural_ode optimizer={name!r}. Use one of: "
            "adabelief, adamw, adam, adan, radam, nadam, nadamw, lion, sgd."
        )

    return optax.chain(*transforms)


def _train_with_optax(*, loss_fn, params, neural_cfg):
    """
    Train params with Optax using a Python outer loop.

    The step function is JIT-compiled, but the outer loop remains in Python so
    progress logging and loss-history TSV export are reliable.
    """
    tx = _make_optax_optimizer(neural_cfg)
    opt_state = tx.init(params)

    @eqx.filter_jit
    def _step(params, opt_state):
        (loss, aux), grads = eqx.filter_value_and_grad(
            lambda p: loss_fn(p, None), has_aux=True
        )(params)

        grads = jax.tree_util.tree_map(
            lambda g: jnp.where(jnp.isfinite(g), g, 0.0), grads
        )

        updates, opt_state = tx.update(grads, opt_state, params)
        params = eqx.apply_updates(params, updates)
        return params, opt_state, loss, aux

    steps = int(neural_cfg.steps)
    print_every = max(1, int(getattr(neural_cfg, "print_every", 1)))

    _neural_loss_history.clear()
    t0 = time.perf_counter()
    time_history: list[float] = []

    last_loss = None
    last_aux = None

    for step in range(steps):
        _step_t0 = time.perf_counter()
        params, opt_state, loss, aux = _step(params, opt_state)

        if step % print_every == 0 or step == steps - 1:
            loss.block_until_ready()

            _dt = time.perf_counter() - _step_t0
            elapsed = time.perf_counter() - t0
            avg_step_s = elapsed / max(1, step + 1)
            eta_s = avg_step_s * max(0, steps - step - 1)

            time_history.append(_dt)
            vals = _aux_to_floats(aux)

            _append_neural_loss_history(
                loss=float(loss),
                f_phospho=vals[0],
                f_abund=vals[1],
                f_mrna=vals[2],
                f_k_prior=vals[3],
                f_s_prior=vals[4],
                f_theta_prior=vals[5],
                f_traj_prior=vals[6],
                force_print=False,
                log_to_console=False,
            )

            logger.info(
                "[neural_ode] step=%04d/%04d  "
                "loss=%.4e  phospho=%.4e  abund=%.4e  mrna=%.4e  "
                "k_prior=%.4e  s_prior=%.4e  theta_prior=%.4e  traj_prior=%.4e  "
                "step_t=%.2fs  avg_step=%.2fs  elapsed=%.1fmin  eta=%.1fmin",
                step,
                steps,
                float(loss),
                vals[0],
                vals[1],
                vals[2],
                vals[3],
                vals[4],
                vals[5],
                vals[6],
                _dt,
                avg_step_s,
                elapsed / 60.0,
                eta_s / 60.0,
            )

        else:
            time_history.append(time.perf_counter() - _step_t0)

        last_loss = loss
        last_aux = aux

    if last_loss is not None:
        last_loss.block_until_ready()
    jax.effects_barrier()

    elapsed = time.perf_counter() - t0
    return params, float(last_loss), last_aux, elapsed, time_history

def _train_with_optax_scan(*, loss_fn, params, neural_cfg):
    """
    Train params with Optax using a single JIT-compiled lax.scan loop.

    This reduces Python overhead but does not provide live per-step logging.
    Loss history is collected on-device and appended after the scan completes.
    Use this when you want speed over live progress output.
    """
    tx = _make_optax_optimizer(neural_cfg)
    opt_state = tx.init(params)

    @eqx.filter_jit
    def _run_scan(params, opt_state):
        def _one_step(carry, _):
            params, opt_state = carry

            (loss, aux), grads = eqx.filter_value_and_grad(
                lambda p: loss_fn(p, None),
                has_aux=True,
            )(params)

            grads = jax.tree_util.tree_map(
                lambda g: jnp.where(jnp.isfinite(g), g, 0.0),
                grads,
            )

            updates, opt_state = tx.update(grads, opt_state, params)
            params = eqx.apply_updates(params, updates)

            # aux is fixed 7-field tuple:
            # phospho, abundance, mrna, k_prior, s_prior, theta_prior, traj_prior
            log_row = jnp.stack(
                (
                    loss,
                    aux[0],
                    aux[1],
                    aux[2],
                    aux[3],
                    aux[4],
                    aux[5],
                    aux[6],
                )
            )

            return (params, opt_state), log_row

        (params, opt_state), logs = jax.lax.scan(
            _one_step,
            (params, opt_state),
            xs=None,
            length=int(neural_cfg.steps),
        )
        return params, opt_state, logs

    _neural_loss_history.clear()
    t0 = time.perf_counter()

    params, opt_state, logs = _run_scan(params, opt_state)
    logs.block_until_ready()
    jax.effects_barrier()

    elapsed = time.perf_counter() - t0

    logs_np = np.asarray(logs, dtype=np.float64)
    print_every = max(1, int(getattr(neural_cfg, "print_every", 1)))

    for step, row in enumerate(logs_np):
        if step % print_every == 0 or step == logs_np.shape[0] - 1:
            _append_neural_loss_history(
                loss=row[0],
                f_phospho=row[1],
                f_abund=row[2],
                f_mrna=row[3],
                f_k_prior=row[4],
                f_s_prior=row[5],
                f_theta_prior=row[6],
                f_traj_prior=row[7],
                force_print=True,
                log_to_console=False,
            )
        else:
            _neural_loss_history.append(
                {
                    "step": step,
                    "neural_loss_total": float(row[0]),
                    "neural_loss_phospho": float(row[1]),
                    "neural_loss_abundance": float(row[2]),
                    "neural_loss_mrna": float(row[3]),
                    "neural_loss_k_act_prior": float(row[4]),
                    "neural_loss_s_prod_prior": float(row[5]),
                    "neural_loss_theta_prior": float(row[6]),
                    "neural_loss_traj_prior": float(row[7]),
                }
            )

    final_loss = float(logs_np[-1, 0])
    final_aux = tuple(jnp.asarray(x, dtype=jnp.float64) for x in logs_np[-1, 1:])

    return params, final_loss, final_aux, elapsed

def _block_until_ready_tree(tree) -> None:
    """Synchronise a JAX pytree."""
    for leaf in jax.tree_util.tree_leaves(tree):
        if hasattr(leaf, "block_until_ready"):
            leaf.block_until_ready()
    jax.effects_barrier()


def _train_with_lbfgs_polish(*, loss_fn, params, neural_cfg):
    """
    Post-Optax L-BFGS polish stage using Optimistix.

    Runs L-BFGS in chunks of `print_every` steps so progress is visible without
    relying on Optimistix internal verbose callbacks.
    """
    polish_steps = int(getattr(neural_cfg, "lbfgs_steps", 0))
    if polish_steps <= 0:
        return params, None, None, 0.0, "lbfgs_skipped"

    print_every = max(1, int(getattr(neural_cfg, "print_every", 1)))
    chunk_steps = min(print_every, polish_steps)

    rtol = float(getattr(neural_cfg, "lbfgs_rtol", 1e-8))
    atol = float(getattr(neural_cfg, "lbfgs_atol", 1e-8))
    history_length = int(getattr(neural_cfg, "lbfgs_history_length", 10))
    use_inverse = bool(getattr(neural_cfg, "lbfgs_use_inverse", True))

    solver = optx.LBFGS(
        rtol=rtol,
        atol=atol,
        history_length=history_length,
        use_inverse=use_inverse,
    )

    logger.info(
        "[neural_ode] Starting Optimistix L-BFGS polish: steps=%d, "
        "print_every=%d, rtol=%.2e, atol=%.2e, history_length=%d, use_inverse=%s",
        polish_steps,
        print_every,
        rtol,
        atol,
        history_length,
        use_inverse,
    )

    t0 = time.perf_counter()
    done = 0
    last_loss = None
    last_aux = None
    last_result = "lbfgs_not_started"

    while done < polish_steps:
        n_steps = min(chunk_steps, polish_steps - done)
        chunk_t0 = time.perf_counter()

        result = optx.minimise(
            loss_fn,
            solver,
            params,
            args=None,
            has_aux=True,
            max_steps=n_steps,
            throw=False,
        )

        params = result.value
        _block_until_ready_tree(params)

        loss, aux = loss_fn(params, None)
        loss.block_until_ready()

        vals = _aux_to_floats(aux)
        done += n_steps
        chunk_dt = time.perf_counter() - chunk_t0
        elapsed = time.perf_counter() - t0
        avg_step_s = elapsed / max(1, done)
        eta_s = avg_step_s * max(0, polish_steps - done)

        _append_neural_loss_history(
            loss=float(loss),
            f_phospho=vals[0],
            f_abund=vals[1],
            f_mrna=vals[2],
            f_k_prior=vals[3],
            f_s_prior=vals[4],
            f_theta_prior=vals[5],
            f_traj_prior=vals[6],
            force_print=False,
            log_to_console=False,
        )

        logger.info(
            "[neural_ode][lbfgs] step=%04d/%04d  "
            "loss=%.4e  phospho=%.4e  abund=%.4e  mrna=%.4e  "
            "k_prior=%.4e  s_prior=%.4e  theta_prior=%.4e  traj_prior=%.4e  "
            "chunk_t=%.2fs  avg_step=%.2fs  elapsed=%.1fmin  eta=%.1fmin  result=%s",
            done,
            polish_steps,
            float(loss),
            vals[0],
            vals[1],
            vals[2],
            vals[3],
            vals[4],
            vals[5],
            vals[6],
            chunk_dt,
            avg_step_s,
            elapsed / 60.0,
            eta_s / 60.0,
            str(result.result),
        )

        last_loss = loss
        last_aux = aux
        last_result = str(result.result)

        if not np.isfinite(float(loss)):
            logger.warning(
                "[neural_ode][lbfgs] stopping polish early because loss is non-finite."
            )
            break

    total_elapsed = time.perf_counter() - t0
    return params, float(last_loss), last_aux, total_elapsed, last_result
