def run_neural_latent_rate_refinement(
    *,
    dims: ModelDims | None = None,
    problem,
    theta_best: np.ndarray,
    k_act_fn,
    s_prod_fn,
    t: np.ndarray,
    P_scaled: np.ndarray,
    A_scaled: np.ndarray,
    prot_idx_for_A: np.ndarray,
    W_data: np.ndarray,
    W_data_prot: np.ndarray,
    proteins: list,
    sites: list,
    kinases: list,
    t_rna: Optional[np.ndarray],
    rna_obs_matched: Optional[np.ndarray],
    rna_model_prot_idx: Optional[np.ndarray],
    W_data_mrna_matched: Optional[np.ndarray],
    outdir: str,
    neural_cfg,
    mechanism: str = "dist",
    rna_relax: float = 0.1,
    abundance_max: float = 5.0,
    R_data0: Optional[np.ndarray] = None,
    jaxpr_out_dir=None,
) -> tuple:
    """Run post-fit neural latent-rate refinement.

    Returns:
        tuple: ``(ts, ys, model_opt, loss_history, time_history)`` where:
            - ``ts``           – ``np.ndarray`` of time points used for evaluation.
            - ``ys``           – ``dict`` with keys ``"P_sim"`` and ``"A_sim"``
                                 (dense trajectory arrays from the final neural model).
            - ``model_opt``    – the trained Equinox neural model.
            - ``loss_history`` – ``list[float]`` of total loss per logged step.
            - ``time_history`` – ``list[float]`` of per-step wall-clock time (s).
                                 Only populated for the Optax Python loop; empty for
                                 scan/Optimistix paths.
    """
    if dims is None:
        dims = ModelDims.set_dims(len(proteins), len(kinases), len(sites))
    K = dims.K
    M = dims.M
    N = dims.N

    neural_outdir = os.path.join(outdir, "neural_ode")
    os.makedirs(neural_outdir, exist_ok=True)

    learn_theta = bool(getattr(neural_cfg, "learn_theta", False))
    use_optax = bool(getattr(neural_cfg, "use_optax", True))

    global _neural_log_every
    _neural_log_every = int(getattr(neural_cfg, "print_every", 1))

    logger.info("[neural_ode] Starting post-fit neural latent-rate refinement.")
    logger.info(
        "[neural_ode] Config: width=%d, depth=%d, steps=%d, lr=%.4g, seed=%d, "
        "learn_theta=%s, use_optax=%s, optimizer=%s",
        int(neural_cfg.width),
        int(neural_cfg.depth),
        int(neural_cfg.steps),
        float(neural_cfg.learning_rate),
        int(neural_cfg.seed),
        learn_theta,
        use_optax,
        getattr(neural_cfg, "optimizer", "adabelief"),
    )

    # ------------------------------------------------------------------
    # 1. Evaluate mechanistic prior trajectories at observed time points
    # ------------------------------------------------------------------
    t_obs = np.sort(np.unique(t)).astype(np.float64)
    T_obs = len(t_obs)

    k_act_init_vals, s_prod_init_vals, prior_eval_mode = _evaluate_mechanistic_rate_priors(
        k_act_fn,
        s_prod_fn,
        t_obs,
    )

    logger.info(
        "[neural_ode] Mechanistic prior trajectories computed at %d observed time points using %s.",
        T_obs,
        prior_eval_mode,
    )

    # ------------------------------------------------------------------
    # 2. Build initial ODE state
    # ------------------------------------------------------------------
    T_prot = P_scaled.shape[1]
    A0_full = build_full_A0(K, T_prot, A_scaled, prot_idx_for_A)

    x0 = np.zeros(3 * K + M + N, dtype=np.float64)
    if R_data0 is not None:
        r_data = np.asarray(R_data0, dtype=np.float64)
        r0 = r_data[:, 0].copy() if r_data.ndim > 1 else r_data.copy()
        r0 = np.nan_to_num(r0, nan=1.0, posinf=5.0, neginf=0.0)
        x0[:K] = np.clip(r0, 0.0, 10.0)
    else:
        x0[:K] = 1.0

    a0 = np.nan_to_num(A0_full[:, 0], nan=1.0, posinf=5.0, neginf=0.0)
    x0[2 * K : 3 * K] = np.clip(a0, 0.0, abundance_max)

    p0 = np.nan_to_num(P_scaled[:, 0], nan=0.0, posinf=10.0, neginf=0.0)
    x0[3 * K + M :] = np.clip(p0, 0.0, None)

    # ------------------------------------------------------------------
    # 3. Build JAX arrays
    # ------------------------------------------------------------------
    if t_rna is not None and len(t_rna) > 0:
        all_times = np.sort(np.union1d(t, t_rna)).astype(np.float64)
    else:
        all_times = np.sort(np.unique(t)).astype(np.float64)

    prot_time_idx = np.searchsorted(all_times, t)
    if t_rna is not None and len(t_rna) > 0:
        mrna_time_idx = np.searchsorted(all_times, t_rna)
    else:
        mrna_time_idx = None

    t0_val = float(all_times[0])
    t1_val = float(all_times[-1])
    t_max = float(all_times[-1]) if float(all_times[-1]) > 0 else 1.0

    Cg = np.asarray(problem.Cg)
    Cl = np.asarray(problem.Cl)
    K_site_kin = np.asarray(problem.K_site_kin)
    R = np.asarray(problem.R)
    L_alpha = np.asarray(problem.L_alpha)
    site_prot_idx = np.asarray(problem.site_prot_idx, dtype=np.int32)
    kin_to_prot_idx = np.asarray(problem.kin_to_prot_idx, dtype=np.int32)
    receptor_mask_prot = np.asarray(problem.receptor_mask_prot)
    receptor_mask_kin = np.asarray(problem.receptor_mask_kin)

    prev_site_idx = compute_prev_site_idx(site_prot_idx, N)

    theta_j = jnp.asarray(theta_best, dtype=jnp.float64)
    y0_j = jnp.asarray(x0, dtype=jnp.float64)
    t_eval_j = jnp.asarray(all_times, dtype=jnp.float64)
    prot_idx_solver_j = jnp.asarray(prot_time_idx, dtype=jnp.int32)
    prev_site_idx_j = jnp.asarray(prev_site_idx, dtype=jnp.int32)

    Cg_j = jnp.asarray(Cg, dtype=jnp.float64)
    Cl_j = jnp.asarray(Cl, dtype=jnp.float64)
    K_sk_j = jnp.asarray(K_site_kin, dtype=jnp.float64)
    R_j = jnp.asarray(R, dtype=jnp.float64)
    La_j = jnp.asarray(L_alpha, dtype=jnp.float64)
    spi_j = jnp.asarray(site_prot_idx, dtype=jnp.int32)
    k2p_j = jnp.asarray(kin_to_prot_idx, dtype=jnp.int32)
    rmp_j = jnp.asarray(receptor_mask_prot, dtype=jnp.float64)
    rmk_j = jnp.asarray(receptor_mask_kin, dtype=jnp.float64)

    P_data_j = jnp.asarray(P_scaled, dtype=jnp.float64)
    A_scaled_j = jnp.asarray(A_scaled, dtype=jnp.float64)
    prot_idx_j = jnp.asarray(prot_idx_for_A, dtype=jnp.int32)
    W_data_j = jnp.asarray(W_data, dtype=jnp.float64)
    W_prot_j = jnp.asarray(W_data_prot, dtype=jnp.float64)

    t_obs_j = jnp.asarray(t_obs, dtype=jnp.float64)
    k_act_init_obs_j = jnp.asarray(k_act_init_vals, dtype=jnp.float64)
    s_prod_init_obs_j = jnp.asarray(s_prod_init_vals, dtype=jnp.float64)

    has_mrna = (
        t_rna is not None
        and rna_obs_matched is not None
        and len(t_rna) > 0
        and mrna_time_idx is not None
        and rna_model_prot_idx is not None
        and len(rna_model_prot_idx) > 0
    )

    if has_mrna:
        rna_j = jnp.asarray(rna_obs_matched, dtype=jnp.float64)
        mrna_idx_j = jnp.asarray(mrna_time_idx, dtype=jnp.int32)
        rna_prot_idx_j = jnp.asarray(rna_model_prot_idx, dtype=jnp.int32)
        n_matched = len(rna_model_prot_idx)
        T_rna = len(t_rna)
        W_rna_base = (
            np.asarray(W_data_mrna_matched, dtype=np.float64)
            if W_data_mrna_matched is not None
            else np.ones((n_matched, T_rna), dtype=np.float64)
        )
        W_rna_j = jnp.asarray(W_rna_base, dtype=jnp.float64)
    else:
        rna_j = mrna_idx_j = rna_prot_idx_j = W_rna_j = None

    # ------------------------------------------------------------------
    # 4. Build model and loss function
    # ------------------------------------------------------------------
    key = jax.random.PRNGKey(int(neural_cfg.seed))

    if learn_theta:
        model = JointNeuralMechanisticModel(
            K=K,
            width=int(neural_cfg.width),
            depth=int(neural_cfg.depth),
            theta_best=np.asarray(theta_best, dtype=np.float64),
            key=key,
        )
        params, static = eqx.partition(model, eqx.is_array)

        theta_lower_j = None
        theta_upper_j = None
        if hasattr(problem, "xl") and hasattr(problem, "xu"):
            theta_lower_j = jnp.asarray(problem.xl, dtype=jnp.float64)
            theta_upper_j = jnp.asarray(problem.xu, dtype=jnp.float64)

        logger.info(
            "[neural_ode] JointNeuralMechanisticModel created with trainable theta."
        )

        xs_mech_ref_j = _solve_mechanistic_reference(
            K=K,
            M=M,
            N=N,
            mechanism=mechanism,
            theta_j=theta_j,
            y0_j=y0_j,
            t0_val=t0_val,
            t1_val=t1_val,
            t_eval_j=t_eval_j,
            prev_site_idx_j=prev_site_idx_j,
            Cg_j=Cg_j,
            Cl_j=Cl_j,
            K_sk_j=K_sk_j,
            R_j=R_j,
            La_j=La_j,
            spi_j=spi_j,
            k2p_j=k2p_j,
            rmp_j=rmp_j,
            rmk_j=rmk_j,
            k_act_fn=k_act_fn,
            s_prod_fn=s_prod_fn,
            rtol=float(neural_cfg.rtol),
            atol=float(neural_cfg.atol),
            dt0=float(neural_cfg.dt0),
            max_steps=int(neural_cfg.max_steps),
            rna_relax=float(rna_relax),
            abundance_max=float(abundance_max),
        )

        neural_loss_fn = _make_joint_loss_fn(
            K=K,
            M=M,
            N=N,
            mechanism=mechanism,
            theta_init_j=theta_j,
            theta_lower_j=theta_lower_j,
            theta_upper_j=theta_upper_j,
            xs_mech_ref_j=xs_mech_ref_j,
            y0_j=y0_j,
            t0_val=t0_val,
            t1_val=t1_val,
            t_eval_j=t_eval_j,
            prot_idx_solver_j=prot_idx_solver_j,
            prev_site_idx_j=prev_site_idx_j,
            Cg_j=Cg_j,
            Cl_j=Cl_j,
            K_sk_j=K_sk_j,
            R_j=R_j,
            La_j=La_j,
            spi_j=spi_j,
            k2p_j=k2p_j,
            rmp_j=rmp_j,
            rmk_j=rmk_j,
            P_data_j=P_data_j,
            A_scaled_j=A_scaled_j,
            prot_idx_j=prot_idx_j,
            W_data_j=W_data_j,
            W_prot_j=W_prot_j,
            t_obs_j=t_obs_j,
            k_act_init_obs_j=k_act_init_obs_j,
            s_prod_init_obs_j=s_prod_init_obs_j,
            t_max=t_max,
            has_mrna=has_mrna,
            rna_j=rna_j,
            mrna_idx_j=mrna_idx_j,
            rna_prot_idx_j=rna_prot_idx_j,
            W_rna_j=W_rna_j,
            w_phospho=float(neural_cfg.data_weight_phospho),
            w_abundance=float(neural_cfg.data_weight_abundance),
            w_mrna=float(neural_cfg.data_weight_mrna),
            prior_weight_k_act=float(neural_cfg.prior_weight_k_act),
            prior_weight_s_prod=float(neural_cfg.prior_weight_s_prod),
            prior_weight_theta=float(getattr(neural_cfg, "prior_weight_theta", 10.0)),
            prior_weight_traj=float(getattr(neural_cfg, "prior_weight_traj", 0.1)),
            rtol=float(neural_cfg.rtol),
            atol=float(neural_cfg.atol),
            dt0=float(neural_cfg.dt0),
            max_steps=int(neural_cfg.max_steps),
            rna_relax=float(rna_relax),
            abundance_max=float(abundance_max),
            k_act_init_fn=k_act_fn,
            s_prod_init_fn=s_prod_fn,
            static=static,
        )
    else:
        model = NeuralRateGenerator(
            K=K,
            width=int(neural_cfg.width),
            depth=int(neural_cfg.depth),
            key=key,
        )
        params, static = eqx.partition(model, eqx.is_array)

        logger.info("[neural_ode] NeuralRateGenerator created with frozen theta.")

        neural_loss_fn = _make_neural_loss_fn(
            K=K,
            M=M,
            N=N,
            mechanism=mechanism,
            theta_j=theta_j,
            y0_j=y0_j,
            t0_val=t0_val,
            t1_val=t1_val,
            t_eval_j=t_eval_j,
            prot_idx_solver_j=prot_idx_solver_j,
            prev_site_idx_j=prev_site_idx_j,
            Cg_j=Cg_j,
            Cl_j=Cl_j,
            K_sk_j=K_sk_j,
            R_j=R_j,
            La_j=La_j,
            spi_j=spi_j,
            k2p_j=k2p_j,
            rmp_j=rmp_j,
            rmk_j=rmk_j,
            P_data_j=P_data_j,
            A_scaled_j=A_scaled_j,
            prot_idx_j=prot_idx_j,
            W_data_j=W_data_j,
            W_prot_j=W_prot_j,
            t_obs_j=t_obs_j,
            k_act_init_obs_j=k_act_init_obs_j,
            s_prod_init_obs_j=s_prod_init_obs_j,
            t_max=t_max,
            has_mrna=has_mrna,
            rna_j=rna_j,
            mrna_idx_j=mrna_idx_j,
            rna_prot_idx_j=rna_prot_idx_j,
            W_rna_j=W_rna_j,
            w_phospho=float(neural_cfg.data_weight_phospho),
            w_abundance=float(neural_cfg.data_weight_abundance),
            w_mrna=float(neural_cfg.data_weight_mrna),
            prior_weight_k_act=float(neural_cfg.prior_weight_k_act),
            prior_weight_s_prod=float(neural_cfg.prior_weight_s_prod),
            rtol=float(neural_cfg.rtol),
            atol=float(neural_cfg.atol),
            dt0=float(neural_cfg.dt0),
            max_steps=int(neural_cfg.max_steps),
            rna_relax=float(rna_relax),
            abundance_max=float(abundance_max),
            k_act_init_fn=k_act_fn,
            s_prod_init_fn=s_prod_fn,
            static=static,
        )

    # ------------------------------------------------------------------
    # 5. Optional JAXPR capture
    # ------------------------------------------------------------------
    if jaxpr_out_dir is not None:
        from pathlib import Path as _Path
        from phoscrosstalk.jaxpr_reporter import capture_and_save_jaxpr

        capture_and_save_jaxpr(
            fn=neural_loss_fn,
            example_args=(params, None),
            step_label=(
                "neural_ode_joint_loss_fn" if learn_theta else "neural_ode_loss_fn"
            ),
            module_label="phoscrosstalk.neural_ode",
            out_dir=_Path(jaxpr_out_dir),
        )

    # ------------------------------------------------------------------
    # 6. Initial loss
    # ------------------------------------------------------------------
    logger.info("[neural_ode] Compiling/evaluating neural loss function...")
    loss_init, aux_init = neural_loss_fn(params, None)
    f_p0, f_a0, f_r0, f_k0, f_s0, f_theta0, f_traj0 = _aux_to_floats(aux_init)

    logger.info(
        "[neural_ode] Initial loss: total=%.4g | phospho=%.4g | abund=%.4g "
        "| mrna=%.4g | k_prior=%.4g | s_prior=%.4g | theta_prior=%.4g | traj_prior=%.4g",
        float(loss_init),
        f_p0,
        f_a0,
        f_r0,
        f_k0,
        f_s0,
        f_theta0,
        f_traj0,
    )

    # ------------------------------------------------------------------
    # 7. Train
    # ------------------------------------------------------------------
    if use_optax:
        optax_loop = str(getattr(neural_cfg, "optax_loop", "python")).lower()

        logger.info(
            "[neural_ode] Training with Optax optimizer=%s for %d steps using loop=%s.",
            getattr(neural_cfg, "optimizer", "adabelief"),
            int(neural_cfg.steps),
            optax_loop,
        )

        if optax_loop == "scan":
            params_opt, _train_loss, _train_aux, optax_elapsed = _train_with_optax_scan(
                loss_fn=neural_loss_fn,
                params=params,
                neural_cfg=neural_cfg,
            )
            _optax_time_history: list[float] = []
            train_result_status = "optax_scan_complete"
        else:
            (
                params_opt,
                _train_loss,
                _train_aux,
                optax_elapsed,
                _optax_time_history,
            ) = _train_with_optax(
                loss_fn=neural_loss_fn,
                params=params,
                neural_cfg=neural_cfg,
            )
            train_result_status = "optax_python_complete"

        total_elapsed = optax_elapsed

        if bool(getattr(neural_cfg, "lbfgs_polish", False)):
            (
                params_opt,
                _lbfgs_loss,
                _lbfgs_aux,
                lbfgs_elapsed,
                lbfgs_status,
            ) = _train_with_lbfgs_polish(
                loss_fn=neural_loss_fn,
                params=params_opt,
                neural_cfg=neural_cfg,
            )

            total_elapsed += lbfgs_elapsed
            train_result_status = f"{train_result_status}+{lbfgs_status}"

    else:
        logger.info(
            "[neural_ode] Training with Optimistix GradientDescent for %d steps.",
            int(neural_cfg.steps),
        )
        lr = float(neural_cfg.learning_rate)
        solver = optx.GradientDescent(
            learning_rate=lr,
            rtol=1e-100,
            atol=1e-100,
        )

        _neural_loss_history.clear()
        _optax_time_history = []
        t_total = time.perf_counter()
        train_result = optx.minimise(
            neural_loss_fn,
            solver,
            params,
            args=None,
            has_aux=True,
            max_steps=int(neural_cfg.steps),
            throw=False,
        )
        _block_until_ready_tree(train_result.value)
        total_elapsed = time.perf_counter() - t_total

        params_opt = train_result.value
        train_result_status = str(train_result.result)

    logger.info(
        "[neural_ode] refinement complete result=%s total_t=%.1fs",
        train_result_status,
        total_elapsed,
    )

    # ------------------------------------------------------------------
    # 8. Final loss and model reconstruction
    # ------------------------------------------------------------------
    loss_final, aux_final = neural_loss_fn(params_opt, None)
    f_p_fin, f_a_fin, f_r_fin, f_k_fin, f_s_fin, f_theta_fin, f_traj_fin = _aux_to_floats(
        aux_final
    )

    logger.info(
        "[neural_ode] Final loss: total=%.4g | phospho=%.4g | abund=%.4g "
        "| mrna=%.4g | k_prior=%.4g | s_prior=%.4g | theta_prior=%.4g | traj_prior=%.4g",
        float(loss_final),
        f_p_fin,
        f_a_fin,
        f_r_fin,
        f_k_fin,
        f_s_fin,
        f_theta_fin,
        f_traj_fin,
    )

    model_opt = eqx.combine(params_opt, static)

    if learn_theta:
        theta_refined = np.asarray(model_opt.theta, dtype=np.float64)
        if hasattr(problem, "xl") and hasattr(problem, "xu"):
            theta_refined = np.clip(theta_refined, problem.xl, problem.xu)
        theta_for_outputs_j = jnp.asarray(theta_refined, dtype=jnp.float64)
        neural_model_opt = model_opt.neural

        theta_npz_path = os.path.join(neural_outdir, "joint_refined_theta.npz")
        np.savez(
            theta_npz_path,
            theta_best=np.asarray(theta_best, dtype=np.float64),
            theta_refined=theta_refined,
            delta_theta=theta_refined - np.asarray(theta_best, dtype=np.float64),
        )
        logger.info("[neural_ode] Saved %s", theta_npz_path)
    else:
        theta_refined = np.asarray(theta_best, dtype=np.float64)
        theta_for_outputs_j = theta_j
        neural_model_opt = model_opt

    # ------------------------------------------------------------------
    # 9. Evaluate learned and prior rates at observed time points
    # ------------------------------------------------------------------
    t_norms_obs = np.clip(t_obs / t_max, 0.0, 1.0)[:, None]
    k_priors_obs_np = k_act_init_vals.T
    s_priors_obs_np = s_prod_init_vals.T
    features_obs_np = np.concatenate(
        [t_norms_obs, k_priors_obs_np, s_priors_obs_np], axis=1
    )
    features_obs_j = jnp.asarray(features_obs_np, dtype=jnp.float64)

    k_hats_obs_j, s_hats_obs_j = jax.vmap(neural_model_opt)(features_obs_j)
    k_hats_obs = np.asarray(k_hats_obs_j)
    s_hats_obs = np.asarray(s_hats_obs_j)

    # ------------------------------------------------------------------
    # 10. Save latent rates
    # k_act uses t_rna scale (mRNA-related); s_prod uses t_obs scale.
    # Matches the convention in save_derived_rates / derived_rates_long.tsv.
    # ------------------------------------------------------------------

    # Determine k_act time grid: use t_rna when available (mRNA-related rate).
    if t_rna is not None and len(t_rna) > 0:
        t_kact = np.asarray(t_rna, dtype=np.float64)
        k_act_mech_rna, _, _ = _evaluate_mechanistic_rate_priors(
            k_act_fn, s_prod_fn, t_kact
        )
        # Evaluate neural model at t_rna grid.
        t_norms_rna = np.clip(t_kact / t_max, 0.0, 1.0)[:, None]
        k_priors_rna = k_act_mech_rna.T  # (T_rna, K)
        # s_prod priors at t_rna for features (needed by the NN but not saved).
        s_prod_mech_rna_np = np.vstack(
            [np.asarray(s_prod_fn(float(ti))) for ti in t_kact]
        )  # (T_rna, K)
        features_rna = np.concatenate(
            [t_norms_rna, k_priors_rna, s_prod_mech_rna_np], axis=1
        )
        features_rna_j = jnp.asarray(features_rna, dtype=jnp.float64)
        k_hats_rna_j, _ = jax.vmap(neural_model_opt)(features_rna_j)
        k_hats_rna = np.asarray(k_hats_rna_j)  # (T_rna, K)
    else:
        t_kact = t_obs
        k_act_mech_rna = k_act_init_vals  # (K, T_obs)
        k_hats_rna = k_hats_obs          # (T_obs, K)

    rate_rows = []
    for ti_idx, t_val in enumerate(t_kact):
        for p_idx, prot in enumerate(proteins):
            rate_rows.append(
                {
                    "rate_type": "k_act",
                    "entity": prot,
                    "time": float(t_val),
                    "mechanistic_prior": float(k_act_mech_rna[p_idx, ti_idx]),
                    "neural_learned": float(k_hats_rna[ti_idx, p_idx]),
                    "difference": float(
                        k_hats_rna[ti_idx, p_idx] - k_act_mech_rna[p_idx, ti_idx]
                    ),
                }
            )

    for ti_idx, t_val in enumerate(t_obs):
        for p_idx, prot in enumerate(proteins):
            rate_rows.append(
                {
                    "rate_type": "s_prod",
                    "entity": prot,
                    "time": float(t_val),
                    "mechanistic_prior": float(s_prod_init_vals[p_idx, ti_idx]),
                    "neural_learned": float(s_hats_obs[ti_idx, p_idx]),
                    "difference": float(
                        s_hats_obs[ti_idx, p_idx] - s_prod_init_vals[p_idx, ti_idx]
                    ),
                }
            )

    import pandas as pd  # noqa: PLC0415

    df_rates = pd.DataFrame(rate_rows)
    rates_tsv = os.path.join(neural_outdir, "neural_latent_rates.tsv")
    df_rates.to_csv(rates_tsv, sep="\t", index=False)
    logger.info("[neural_ode] Saved %s", rates_tsv)

    np.savez(
        os.path.join(neural_outdir, "neural_latent_rates.npz"),
        t_obs=t_obs,
        t_kact=t_kact,
        proteins=np.array(proteins),
        k_act_mechanistic=k_act_mech_rna,
        s_prod_mechanistic=s_prod_init_vals,
        k_act_neural=k_hats_rna.T,
        s_prod_neural=s_hats_obs.T,
    )

    # ------------------------------------------------------------------
    # 11. Neural fit timeseries at observed time points
    # ------------------------------------------------------------------
    sim_obs = _neural_simulate_dense(
        model=neural_model_opt,
        K=K,
        M=M,
        N=N,
        mechanism=mechanism,
        theta_j=theta_for_outputs_j,
        y0_j=y0_j,
        t0_val=t0_val,
        t_dense=t_obs,
        prev_site_idx_j=prev_site_idx_j,
        Cg_j=Cg_j,
        Cl_j=Cl_j,
        K_sk_j=K_sk_j,
        R_j=R_j,
        La_j=La_j,
        spi_j=spi_j,
        k2p_j=k2p_j,
        rmp_j=rmp_j,
        rmk_j=rmk_j,
        t_max=t_max,
        k_act_init_fn=k_act_fn,
        s_prod_init_fn=s_prod_fn,
        rtol=float(neural_cfg.rtol),
        atol=float(neural_cfg.atol),
        dt0=float(neural_cfg.dt0),
        max_steps=int(neural_cfg.max_steps),
        rna_relax=float(rna_relax),
        abundance_max=float(abundance_max),
    )

    # Build reverse mapping: protein index → row index in A_scaled.
    # Only proteins in prot_idx_for_A have observed abundance data.
    prot_to_obs_k = {int(prot_idx_for_A[k]): k for k in range(len(prot_idx_for_A))}

    ts_rows = []
    for ti_idx, t_val in enumerate(t_obs):
        for s_idx, site in enumerate(sites):
            ts_rows.append(
                {
                    "time": float(t_val),
                    "entity_type": "phosphosite",
                    "entity": site,
                    "value_neural": float(sim_obs["P_sim"][s_idx, ti_idx]),
                    "value_observed": float(P_scaled[s_idx, ti_idx])
                    if ti_idx < P_scaled.shape[1]
                    else float("nan"),
                }
            )
        for p_idx, prot in enumerate(proteins):
            obs_k = prot_to_obs_k.get(p_idx, None)
            if obs_k is not None and ti_idx < A_scaled.shape[1]:
                obs_val = float(A_scaled[obs_k, ti_idx])
            else:
                obs_val = float("nan")
            ts_rows.append(
                {
                    "time": float(t_val),
                    "entity_type": "abundance",
                    "entity": prot,
                    "value_neural": float(sim_obs["A_sim"][p_idx, ti_idx]),
                    "value_observed": obs_val,
                }
            )

    # mRNA rows: simulate at t_rna and include observed mRNA values.
    if has_mrna and t_rna is not None and len(t_rna) > 0:
        t_rna_arr = np.asarray(t_rna, dtype=np.float64)
        try:
            sim_rna = _neural_simulate_dense(
                model=neural_model_opt,
                K=K,
                M=M,
                N=N,
                mechanism=mechanism,
                theta_j=theta_for_outputs_j,
                y0_j=y0_j,
                t0_val=t0_val,
                t_dense=t_rna_arr,
                prev_site_idx_j=prev_site_idx_j,
                Cg_j=Cg_j,
                Cl_j=Cl_j,
                K_sk_j=K_sk_j,
                R_j=R_j,
                La_j=La_j,
                spi_j=spi_j,
                k2p_j=k2p_j,
                rmp_j=rmp_j,
                rmk_j=rmk_j,
                t_max=t_max,
                k_act_init_fn=k_act_fn,
                s_prod_init_fn=s_prod_fn,
                rtol=float(neural_cfg.rtol),
                atol=float(neural_cfg.atol),
                dt0=float(neural_cfg.dt0),
                max_steps=int(neural_cfg.max_steps),
                rna_relax=float(rna_relax),
                abundance_max=float(abundance_max),
            )
            R_sim_rna = sim_rna["R_sim"]  # (K, T_rna)
            rna_obs_arr = np.asarray(rna_obs_matched, dtype=np.float64)  # (n_matched, T_rna)
            for gene_idx, p_idx in enumerate(rna_model_prot_idx):
                prot_name = proteins[int(p_idx)]
                for ti_idx, t_val in enumerate(t_rna_arr):
                    obs_rna = float(rna_obs_arr[gene_idx, ti_idx]) if ti_idx < rna_obs_arr.shape[1] else float("nan")
                    ts_rows.append(
                        {
                            "time": float(t_val),
                            "entity_type": "mrna",
                            "entity": prot_name,
                            "value_neural": float(R_sim_rna[int(p_idx), ti_idx]),
                            "value_observed": obs_rna,
                        }
                    )
        except Exception as exc:
            logger.warning("[neural_ode] mRNA rows in neural_fit_timeseries.tsv skipped: %s", exc)

    df_ts = pd.DataFrame(ts_rows)
    ts_path = os.path.join(neural_outdir, "neural_fit_timeseries.tsv")
    df_ts.to_csv(ts_path, sep="\t", index=False)
    logger.info("[neural_ode] Saved %s", ts_path)

    # ------------------------------------------------------------------
    # 12. Dense timeseries
    # ------------------------------------------------------------------
    if getattr(neural_cfg, "save_dense", True):
        n_dense = int(getattr(neural_cfg, "dense_n_points", 200))
        t_dense_arr = np.linspace(float(t_obs[0]), float(t_obs[-1]), n_dense)
        sim_dense = _neural_simulate_dense(
            model=neural_model_opt,
            K=K,
            M=M,
            N=N,
            mechanism=mechanism,
            theta_j=theta_for_outputs_j,
            y0_j=y0_j,
            t0_val=t0_val,
            t_dense=t_dense_arr,
            prev_site_idx_j=prev_site_idx_j,
            Cg_j=Cg_j,
            Cl_j=Cl_j,
            K_sk_j=K_sk_j,
            R_j=R_j,
            La_j=La_j,
            spi_j=spi_j,
            k2p_j=k2p_j,
            rmp_j=rmp_j,
            rmk_j=rmk_j,
            t_max=t_max,
            k_act_init_fn=k_act_fn,
            s_prod_init_fn=s_prod_fn,
            rtol=float(neural_cfg.rtol),
            atol=float(neural_cfg.atol),
            dt0=float(neural_cfg.dt0),
            max_steps=int(neural_cfg.max_steps),
            rna_relax=float(rna_relax),
            abundance_max=float(abundance_max),
        )

        dense_rows = []
        for ti_idx, t_val in enumerate(t_dense_arr):
            for s_idx, site in enumerate(sites):
                dense_rows.append(
                    {
                        "time": float(t_val),
                        "entity_type": "phosphosite",
                        "entity": site,
                        "value": float(sim_dense["P_sim"][s_idx, ti_idx]),
                        "series_type": "neural_refined_dense",
                    }
                )
            for p_idx, prot in enumerate(proteins):
                dense_rows.append(
                    {
                        "time": float(t_val),
                        "entity_type": "abundance",
                        "entity": prot,
                        "value": float(sim_dense["A_sim"][p_idx, ti_idx]),
                        "series_type": "neural_refined_dense",
                    }
                )

        df_dense = pd.DataFrame(dense_rows)
        dense_path = os.path.join(neural_outdir, "neural_fit_timeseries_dense.tsv")
        df_dense.to_csv(dense_path, sep="\t", index=False)
        logger.info("[neural_ode] Saved %s", dense_path)

    # ------------------------------------------------------------------
    # 13. Training losses TSV
    # ------------------------------------------------------------------
    if _neural_loss_history:
        df_losses = pd.DataFrame(_neural_loss_history)
    else:
        df_losses = pd.DataFrame(
            [
                {
                    "step": 0,
                    "neural_loss_total": float(loss_init),
                    "neural_loss_phospho": f_p0,
                    "neural_loss_abundance": f_a0,
                    "neural_loss_mrna": f_r0,
                    "neural_loss_k_act_prior": f_k0,
                    "neural_loss_s_prod_prior": f_s0,
                    "neural_loss_theta_prior": f_theta0,
                    "neural_loss_traj_prior": f_traj0,
                },
                {
                    "step": int(neural_cfg.steps),
                    "neural_loss_total": float(loss_final),
                    "neural_loss_phospho": f_p_fin,
                    "neural_loss_abundance": f_a_fin,
                    "neural_loss_mrna": f_r_fin,
                    "neural_loss_k_act_prior": f_k_fin,
                    "neural_loss_s_prod_prior": f_s_fin,
                    "neural_loss_theta_prior": f_theta_fin,
                    "neural_loss_traj_prior": f_traj_fin,
                },
            ]
        )

    losses_path = os.path.join(neural_outdir, "neural_training_losses.tsv")
    df_losses.to_csv(losses_path, sep="\t", index=False)
    logger.info("[neural_ode] Saved %s", losses_path)

    # ------------------------------------------------------------------
    # 14. Metadata JSON
    # ------------------------------------------------------------------
    metadata = {
        "enabled": True,
        "width": int(neural_cfg.width),
        "depth": int(neural_cfg.depth),
        "steps": int(neural_cfg.steps),
        "seed": int(neural_cfg.seed),
        "optimizer": (
            f"optax.{getattr(neural_cfg, 'optimizer', 'adabelief')}"
            if use_optax
            else "optimistix.GradientDescent"
        ),
        "optimizer_note": (
            "Optax uses a Python outer loop with a JIT-compiled step, so per-step "
            "logging and training-loss TSV export are reliable."
            if use_optax
            else "Optimistix GradientDescent path retained for compatibility."
        ),
        "learning_rate": float(neural_cfg.learning_rate),
        "grad_clip": float(getattr(neural_cfg, "grad_clip", 1.0)),
        "weight_decay": float(getattr(neural_cfg, "weight_decay", 0.0)),
        "rtol": float(neural_cfg.rtol),
        "atol": float(neural_cfg.atol),
        "dt0": float(neural_cfg.dt0),
        "max_steps": int(neural_cfg.max_steps),
        "prior_weights": {
            "k_act": float(neural_cfg.prior_weight_k_act),
            "s_prod": float(neural_cfg.prior_weight_s_prod),
            "theta": float(getattr(neural_cfg, "prior_weight_theta", 10.0)),
            "trajectory": float(getattr(neural_cfg, "prior_weight_traj", 0.1)),
        },
        "data_weights": {
            "phospho": float(neural_cfg.data_weight_phospho),
            "abundance": float(neural_cfg.data_weight_abundance),
            "mrna": float(neural_cfg.data_weight_mrna),
        },
        "theta_fixed": not learn_theta,
        "learn_theta": bool(learn_theta),
        "theta_refined_path": "joint_refined_theta.npz" if learn_theta else None,
        "state_variables": ["R", "S", "A", "Kdyn", "P"],
        "initial_loss": float(loss_init),
        "final_loss": float(loss_final),
        "initial_loss_terms": {
            "phospho": f_p0,
            "abundance": f_a0,
            "mrna": f_r0,
            "k_act_prior": f_k0,
            "s_prod_prior": f_s0,
            "theta_prior": f_theta0,
            "trajectory_prior": f_traj0,
        },
        "final_loss_terms": {
            "phospho": f_p_fin,
            "abundance": f_a_fin,
            "mrna": f_r_fin,
            "k_act_prior": f_k_fin,
            "s_prod_prior": f_s_fin,
            "theta_prior": f_theta_fin,
            "trajectory_prior": f_traj_fin,
        },
        "note": (
            "Post-fit latent-rate refinement. If learn_theta is false, theta_best is held fixed. "
            "If learn_theta is true, theta is initialized from theta_best, clipped to bounds when "
            "available, and regularized toward theta_best."
        ),
    }

    meta_path = os.path.join(neural_outdir, "neural_metadata.json")
    with open(meta_path, "w") as fh:
        json.dump(metadata, fh, indent=2)
    logger.info("[neural_ode] Saved %s", meta_path)

    # ------------------------------------------------------------------
    # 15. Save model bundle (reproducible Equinox checkpoint)
    # ------------------------------------------------------------------
    try:
        save_neural_ode_bundle(
            neural_outdir,
            neural_model=neural_model_opt,
            theta_refined=theta_refined,
            neural_cfg=neural_cfg,
            K=K,
            learn_theta=learn_theta,
        )
    except Exception as exc:
        logger.warning("[neural_ode] Could not save model bundle: %s", exc)

    logger.info(
        "[neural_ode] Neural latent-rate refinement complete. Outputs saved to %s/",
        neural_outdir,
    )

    # Build return values: ts (time axis), ys (dense sim at observed times),
    # trained model, loss history, and per-step time history.
    _ts = t_obs
    _ys = sim_obs  # dict with P_sim, A_sim evaluated at t_obs
    _loss_history = [float(row["neural_loss_total"]) for row in _neural_loss_history]
    # _optax_time_history is always assigned in every branch of the training block
    _time_history = _optax_time_history  # noqa: F821

    return _ts, _ys, model_opt, _loss_history, _time_history
