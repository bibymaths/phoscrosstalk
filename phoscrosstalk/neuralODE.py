"""
neuralODE.py
Post-fit neural latent-rate refinement for the phospho-network model.

Implements a Mechanistic Graph-Constrained Latent Neural ODE.

Two training modes are supported:

1. Frozen-theta neural refinement, the original behavior:
   - theta_best is fixed.
   - Only the neural rate generator parameters are trained.
   - k_hat_act(t) and s_hat_prod(t) are regularised toward the mechanistic
     derived-rate priors k_act(t) and s_prod(t).

2. Joint neural + mechanistic refinement:
   - theta is initialized from theta_best and trained together with the
     neural rate generator.
   - theta is regularised toward theta_best.
   - the full ODE trajectory is regularised toward the original mechanistic
     trajectory generated by theta_best.
   - theta is clipped to problem.xl/problem.xu when those bounds are available.

The mechanistic equations are unchanged.  The learned neural rate functions only
replace the derived latent rate closures k_act_fn and s_prod_fn inside the ODE.

Public API
----------
run_neural_latent_rate_refinement(...)
    Main entry point called by main.py after the mechanistic fit.
"""

