class LatentRateMLP(eqx.Module):
    """
    Small MLP that maps a biological feature vector to one K-vector rate.

    The output is strictly positive via softplus(raw * out_scale) + eps.
    """

    mlp: eqx.nn.MLP
    out_scale: jax.Array

    def __init__(
        self,
        in_size: int,
        K: int,
        width: int,
        depth: int,
        key: jax.Array,
    ) -> None:
        self.mlp = eqx.nn.MLP(
            in_size=in_size,
            out_size=K,
            width_size=width,
            depth=depth,
            activation=jax.nn.softplus,
            final_activation=lambda x: x,
            use_bias=True,
            use_final_bias=True,
            dtype=jnp.float64,
            scan=True,
            key=key,
        )
        self.out_scale = jnp.ones(K, dtype=jnp.float64)

    def __call__(self, features: jax.Array) -> jax.Array:
        raw = self.mlp(features)
        return jax.nn.softplus(raw * self.out_scale) + jnp.asarray(
            _EPS, dtype=jnp.float64
        )


class NeuralRateGenerator(eqx.Module):
    """
    Two independent MLPs for k_hat_act(t) and s_hat_prod(t).

    Input feature vector:
        [normalised_time, k_act_init(t), s_prod_init(t)]
    shape:
        (1 + K + K,)
    """

    k_act_net: LatentRateMLP
    s_prod_net: LatentRateMLP

    def __init__(self, K: int, width: int, depth: int, key: jax.Array) -> None:
        in_size = 1 + K + K
        k_key, s_key = jax.random.split(key)
        self.k_act_net = LatentRateMLP(in_size, K, width, depth, k_key)
        self.s_prod_net = LatentRateMLP(in_size, K, width, depth, s_key)

    def __call__(self, features: jax.Array):
        k_hat = self.k_act_net(features)
        s_hat = self.s_prod_net(features)
        return k_hat, s_hat

    def latent_activations(self, features: jax.Array) -> tuple[jax.Array, jax.Array]:
        """Return the final hidden-layer activations of k_act_net and s_prod_net.

        Runs *features* through all hidden layers (with softplus activation applied
        between them) but stops before the final linear output projection.  The
        returned arrays have shape ``(width,)`` and can be used to visualise what
        the network has learned at each time point.

        Note: relies on ``eqx.nn.MLP.layers`` being an indexable sequence of
        ``eqx.nn.Linear`` layers (equinox >= 0.10).  If the MLP was built with
        ``scan=True`` the layers are batched but the sequence interface is still
        supported.

        Returns
        -------
        k_hidden : jax.Array, shape (width,)
            Final hidden-layer activations from the k_act MLP.
        s_hidden : jax.Array, shape (width,)
            Final hidden-layer activations from the s_prod MLP.
        """

        def _last_hidden(latent_mlp: LatentRateMLP, x: jax.Array) -> jax.Array:
            # All linear layers except the final output projection.
            for layer in latent_mlp.mlp.layers[:-1]:
                x = jax.nn.softplus(layer(x))
            return x

        k_hidden = _last_hidden(self.k_act_net, features)
        s_hidden = _last_hidden(self.s_prod_net, features)
        return k_hidden, s_hidden


class JointNeuralMechanisticModel(eqx.Module):
    """
    Joint trainable model: neural rate generator plus mechanistic theta.

    theta is kept in the existing PhosCrosstalk parameterisation.  Do not apply
    softplus to the full theta vector because the flattened theta contains both
    log-rates and raw gamma parameters.
    """

    neural: NeuralRateGenerator
    theta: jax.Array

    def __init__(
        self,
        K: int,
        width: int,
        depth: int,
        theta_best: np.ndarray,
        key: jax.Array,
    ) -> None:
        self.neural = NeuralRateGenerator(K=K, width=width, depth=depth, key=key)
        self.theta = jnp.asarray(theta_best, dtype=jnp.float64)

    def latent_activations(self, features: jax.Array) -> tuple[jax.Array, jax.Array]:
        """Delegate to the wrapped NeuralRateGenerator.latent_activations()."""
        return self.neural.latent_activations(features)


