def _append_neural_loss_history(
    *,
    loss: float,
    f_phospho: float,
    f_abund: float,
    f_mrna: float,
    f_k_prior: float,
    f_s_prior: float,
    f_theta_prior: float = 0.0,
    f_traj_prior: float = 0.0,
    force_print: bool = False,
    log_to_console: bool = True,
) -> None:
    """Append one neural training loss row and optionally print it."""
    step = len(_neural_loss_history)

    row = {
        "step": step,
        "neural_loss_total": float(loss),
        "neural_loss_phospho": float(f_phospho),
        "neural_loss_abundance": float(f_abund),
        "neural_loss_mrna": float(f_mrna),
        "neural_loss_k_act_prior": float(f_k_prior),
        "neural_loss_s_prod_prior": float(f_s_prior),
        "neural_loss_theta_prior": float(f_theta_prior),
        "neural_loss_traj_prior": float(f_traj_prior),
    }
    _neural_loss_history.append(row)

    if log_to_console and (force_print or step % max(1, int(_neural_log_every)) == 0):
        msg = (
            f"[neural_ode]  step={step:04d}  "
            f"loss={float(loss):.4e}  "
            f"phospho={float(f_phospho):.4e}  "
            f"abund={float(f_abund):.4e}  "
            f"mrna={float(f_mrna):.4e}  "
            f"k_prior={float(f_k_prior):.4e}  "
            f"s_prior={float(f_s_prior):.4e}  "
            f"theta_prior={float(f_theta_prior):.4e}  "
            f"traj_prior={float(f_traj_prior):.4e}"
        )
        logger.info(msg)


