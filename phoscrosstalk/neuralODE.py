def _aux_to_floats(aux) -> tuple[float, float, float, float, float, float, float]:
    """Convert a 5- or 7-field aux tuple into a fixed 7-field Python tuple."""
    vals = [float(x) for x in tuple(aux)]
    while len(vals) < 7:
        vals.append(0.0)
    return tuple(vals[:7])  # type: ignore[return-value]


