"""
Optimizer-based uncertainty analysis for PhosCrosstalk model parameters.

This module provides uncertainty estimates for fitted mechanistic ODE parameters
after the main optimisation step has produced a best-fit parameter vector
(`theta_best`). The preferred uncertainty methods are optimizer-based rather
than MCMC-based, because PhosCrosstalk uses bounded, transformed parameters,
Diffrax ODE solves, multiple objective components, and residual-vector
least-squares optimisation.

Primary methods
---------------
1. Residual bootstrap

   The fitted model is simulated at `theta_best`, residuals are computed against
   the observed data, synthetic datasets are generated by resampling those
   residuals, and the model is refitted to each synthetic dataset using the same
   optimisation backend as the original fit.

   This produces an empirical distribution of refitted parameter vectors.

2. Profile likelihood

   Selected parameters are fixed over a grid of values between their bounds.
   For each fixed value, the remaining model parameters are re-optimised. The
   resulting profiled total loss is used to assess practical identifiability.

   Interpretation:
       flat profile       -> weakly identifiable / non-identifiable parameter
       sharp profile      -> well-constrained parameter
       boundary minimum   -> bound-constrained or poorly determined parameter

Expected main.py usage
----------------------
    from phoscrosstalk.posterior import run_optimizer_uncertainty

    run_optimizer_uncertainty(
        outdir=outdir,
        problem=problem,
        theta_best=theta_best,
        posterior_cfg=cfg.posterior,
        theta_names=theta_names,
        w_phospho=args.loss_weight_phospho,
        w_abundance=args.loss_weight_abundance,
        w_reg=args.loss_weight_reg,
        w_mrna=args.loss_weight_mrna,
    )

Configuration
-------------
The uncertainty methods are controlled through the existing [posterior] section
of config.toml for backward compatibility.

Typical configuration:

    [posterior]
    enabled = true
    method = "both"  # "bootstrap", "profile", or "both"

    n_bootstrap = 100
    bootstrap_residual_mode = "case"
    bootstrap_max_steps = 200
    bootstrap_start_jitter = 0.0
    rebuild_s_prod_from_bootstrap = true
    save_prediction_intervals = true

    profile_params = 12
    profile_points = 21
    profile_grid_fraction = 1.0
    profile_fix_lambda = 1e8
    profile_max_steps = 300

Outputs
-------
Written to {outdir}/uncertainty/.

Residual bootstrap outputs:

    bootstrap_samples.npz
    bootstrap_summary.tsv
    bootstrap_failures.tsv
    bootstrap_metadata.json
    bootstrap_parameter_distributions.png
    bootstrap_prediction_intervals/

Profile-likelihood outputs:

    profile_likelihood/profile_likelihood.tsv
    profile_likelihood/profile_thetas.npz
    profile_likelihood/profile_metadata.json
    profile_likelihood/profile_param_*.png

Summary columns
---------------
Bootstrap summaries contain:

    parameter
    mean
    std
    median
    q2.5
    q25
    q75
    q97.5
    min
    max
    n_success

Design notes
------------
All refits reuse the existing optimisation machinery rather than introducing a
new statistical backend. This keeps uncertainty estimation consistent with the
actual fitted objective, including phosphosite, abundance, mRNA, regularisation,
loss weights, bounds, solver settings, and backend-specific optimisation logic.
"""

