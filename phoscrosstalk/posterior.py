def _residuals_fn_from_refit_kwargs(refit_kwargs: dict):
    from phoscrosstalk.derived_rates import make_k_act_fn, make_s_prod_fn  # noqa: PLC0415
    from phoscrosstalk.optimization import make_residuals_fn  # noqa: PLC0415

    kwargs = dict(refit_kwargs)

    if "_k_act_rebuild_kwargs" in kwargs:
        k_kwargs = kwargs.pop("_k_act_rebuild_kwargs")
        kwargs["k_act_fn"] = make_k_act_fn(**k_kwargs)

    if "_s_prod_rebuild_kwargs" in kwargs:
        s_kwargs = kwargs.pop("_s_prod_rebuild_kwargs")
        kwargs["s_prod_fn"] = make_s_prod_fn(**s_kwargs)

    return make_residuals_fn(**kwargs)

def _bootstrap_refit_worker(task):
    """
    Process worker for one bootstrap refit.

    Must be top-level so it is picklable. Applies CPU/XLA env before importing
    optimization/JAX-heavy code.
    """
    (
        b,
        theta0,
        refit_kwargs,
        P_boot,
        A_boot,
        R_boot,
        max_steps,
        rtol,
        atol,
        ls_solver,
        optx_adjoint,
        jac_mode,
        threads_per_worker,
        rebuild_s_prod_from_bootstrap,
    ) = task

    from phoscrosstalk import runtime_env  # noqa: PLC0415

    runtime_env.apply_cpu_env(int(threads_per_worker), overwrite=True)

    try:
        from phoscrosstalk.optimization import run_single_optimisation  # noqa: PLC0415

        kwargs = dict(refit_kwargs)
        kwargs["P_data"] = np.asarray(P_boot, dtype=np.float64)

        if A_boot is not None:
            kwargs["A_scaled"] = np.asarray(A_boot, dtype=np.float64)

        if R_boot is not None:
            kwargs["rna_data_scaled"] = np.asarray(R_boot, dtype=np.float64)

        if rebuild_s_prod_from_bootstrap and "_s_prod_rebuild_kwargs" in kwargs:
            s_kwargs = dict(kwargs["_s_prod_rebuild_kwargs"])
            if "Y_data" in s_kwargs:
                s_kwargs["Y_data"] = np.asarray(P_boot, dtype=np.float64)
            kwargs["_s_prod_rebuild_kwargs"] = s_kwargs

        residuals_fn = _residuals_fn_from_refit_kwargs(kwargs)

        theta_opt, total_loss, f1, f2, f3, f4 = run_single_optimisation(
            residuals_fn,
            np.asarray(theta0, dtype=np.float64),
            max_steps=int(max_steps),
            rtol=float(rtol),
            atol=float(atol),
            verbose=False,
            ls_solver=str(ls_solver),
            optx_adjoint=str(optx_adjoint),
            jac_mode=str(jac_mode),
        )

        return (
            int(b),
            True,
            np.asarray(theta_opt, dtype=np.float64),
            float(total_loss),
            float(f1),
            float(f2),
            float(f3),
            float(f4),
            "",
        )

    except Exception as exc:
        return (
            int(b),
            False,
            None,
            np.nan,
            np.nan,
            np.nan,
            np.nan,
            np.nan,
            f"{type(exc).__name__}: {exc}",
        )

def _cfg_get(cfg, name: str, default):
    """Small helper that supports SimpleNamespace-like config objects."""
    if cfg is None:
        return default
    return getattr(cfg, name, default)


def _as_optional_array(x, *, dtype=np.float64):
    if x is None:
        return None
    arr = np.asarray(x, dtype=dtype)
    return arr


def _clip_theta_open(theta, xl, xu, rel_eps: float = 1e-10, abs_eps: float = 1e-12):
    """Clip theta into the open interval (xl, xu) for stable refit starts."""
    theta = np.asarray(theta, dtype=np.float64)
    xl = np.asarray(xl, dtype=np.float64)
    xu = np.asarray(xu, dtype=np.float64)
    span = xu - xl
    eps = np.maximum(rel_eps * span, abs_eps)
    return np.clip(theta, xl + eps, xu - eps)


def _rebuild_rate_functions_for_refit(problem, *, P_data_for_s_prod=None):
    """
    Rebuild k_act_fn and s_prod_fn from picklable kwargs when available.

    For bootstrap refits, s_prod_fn can optionally be rebuilt using the
    bootstrapped phosphosite data. This keeps the derived synthesis prior
    internally consistent with the synthetic dataset.
    """
    k_act_fn = getattr(problem, "k_act_fn", None)
    s_prod_fn = getattr(problem, "s_prod_fn", None)

    k_kwargs = getattr(problem, "_k_act_rebuild_kwargs", None)
    if k_kwargs is not None:
        from phoscrosstalk.derived_rates import make_k_act_fn  # noqa: PLC0415

        k_act_fn = make_k_act_fn(**dict(k_kwargs))

    s_kwargs = getattr(problem, "_s_prod_rebuild_kwargs", None)
    if s_kwargs is not None:
        from phoscrosstalk.derived_rates import make_s_prod_fn  # noqa: PLC0415

        s_kwargs = dict(s_kwargs)
        if P_data_for_s_prod is not None and "Y_data" in s_kwargs:
            s_kwargs["Y_data"] = np.asarray(P_data_for_s_prod, dtype=np.float64)
        s_prod_fn = make_s_prod_fn(**s_kwargs)

    return k_act_fn, s_prod_fn


