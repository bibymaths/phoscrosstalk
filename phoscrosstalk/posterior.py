def _plan_uncertainty_runtime(problem, posterior_cfg, *, n_tasks: int, label: str):
    from phoscrosstalk.runtime_env import plan_cpu_runtime  # noqa: PLC0415

    args = _make_runtime_args_from_problem(
        problem,
        posterior_cfg,
        n_tasks=n_tasks,
    )

    plan = plan_cpu_runtime(
        cpu_threads=args.cpu_threads,
        n_starts=args.n_starts,
        parallel_starts=args.parallel_starts,
        threads_per_start=args.threads_per_start,
        reserve_cores=args.reserve_cores,
        use_physical_cores=args.use_physical_cores,
    )

    topo = plan.topo

    logger.info(
        "[%s/runtime] CPU plan:"
        "\n    SLURM active         = %s"
        "\n    logical CPUs         = %s"
        "\n    physical cores       = %s"
        "\n    affinity CPUs        = %s"
        "\n    usable CPUs          = %s"
        "\n    CPU source           = %s"
        "\n    tasks                = %s"
        "\n    parallel workers     = %s"
        "\n    threads per worker   = %s"
        "\n    XLA intra-op threads = %s"
        "\n    BLAS/OpenMP threads  = %s",
        label,
        topo.slurm_cpus is not None,
        topo.logical_cpus,
        topo.physical_cores if topo.physical_cores is not None else "unknown",
        topo.affinity_cpus if topo.affinity_cpus is not None else "n/a",
        plan.total_available_cpus,
        topo.source,
        n_tasks,
        plan.n_parallel_runs,
        plan.threads_per_run,
        plan.xla_threads,
        plan.blas_threads,
    )

    return plan

